"""Quality gates on the .pyi stubs generated by pybind11-stubgen.

    check_python_stubs.py stubs <directory or .pyi file>... [--allow Class.method]
    check_python_stubs.py stubtest <module>... [--mypy-config-file <ini>]
                          [--stubs-from <directory>]
    check_python_stubs.py modules <module>... [--mypy-config-file <ini>]
                          [--no-stubtest]
    check_python_stubs.py fix <directory or .pyi file>...

`fix` rewrites in place what pybind11-stubgen cannot write: a module-level
TypeVar of a pure-Python module (e.g. `_T = typing.TypeVar("_T")`, used by the
generic functions of basic.py) is written `_T: typing.TypeVar`, which type
checkers reject; it becomes `_T = typing.TypeVar("_T")`. Only plain TypeVars
are supported (stubgen keeps no bound nor constraint). `modules` applies it.

`stubs` fails if a stub contains
  - a parameter named arg0, arg1... (a binding without pybind11::arg),
  - an unresolved annotation (`...` other than in Callable[..., R] or
    tuple[T, ...], or a raw C++ type name: geode::, absl::, std::), in a
    parameter, a return type or a default value,
  - a TypeVar written as an annotation (`_T: typing.TypeVar`, see `fix`).
Only the members generated by pybind11::bind_vector (the dunder methods
__init__, __getitem__, __setitem__ and __delitem__ of a class that also has
append, extend and pop) may keep arg0/arg1, since pybind11 gives no way to name
them. --allow Class.method adds an explicit exception.

`stubtest` runs mypy.stubtest on the modules, ignoring only the differences
between the stubs and the runtime that come from pybind11 itself (see
PYBIND11_ARTEFACTS). Python must be able to import the modules (PYTHONPATH...).
The stubs are found by mypy through MYPYPATH, or --stubs-from <package directory>:
the .pyi files of the package directory, whatever the other files it contains (the sources
of the package, its data...), are copied aside and put on the MYPYPATH.
"""

import argparse
import ast
import os
import re
import shutil
import subprocess
import sys
import tempfile

ARG_NAME = re.compile(r"arg\d+")
RAW_CPP_NAME = re.compile(r"\b(geode|absl|std)::")
TYPEVAR_ANNOTATION = re.compile(r"^(\w+): typing\.TypeVar[ \t]*$", re.M)
BIND_VECTOR_MEMBERS = {"__init__", "__getitem__", "__setitem__", "__delitem__"}
BIND_VECTOR_MARKERS = {"append", "extend", "pop"}

# Messages of mypy.stubtest caused by pybind11, not by a binding:
PYBIND11_ARTEFACTS = [
    # every pybind11 class has the metaclass pybind11_type
    r"\S+ is inconsistent, metaclass differs",
    # classes without constructor: pybind11 defines __init__(self, *args, **kwargs)
    r"\S+\.__init__ is inconsistent, stub does not have \*args parameter",
    # pybind11 enums: stubgen writes the members as annotations, so the stub
    # enum has no member and stubtest compares the runtime Enum.__new__
    r"\S+\.__new__ is inconsistent, stub parameter \"value\" differs",
    r"\S+\.__new__ is inconsistent, stub does not have parameter \"value\"",
    r"\S+\.__pybind11_native_enum__ is not present in stub",
    # pybind11 module-local type registration marker
    r"\S+\.__pybind11_module_local_\w+__ is not present in stub",
    # stubgen writes __all__, the compiled modules have none
    r"\S+\.__all__ is not present at runtime",
    # the fields of a namedtuple (ProgressEvent) are not written by stubgen
    r"\S+ is not present in stub\nStub: [^\n]*\nMISSING\nRuntime:\n_tuplegetter\(",
]


def _is_ellipsis(node):
    return isinstance(node, ast.Constant) and node.value is Ellipsis


def _typing_ellipses(node):
    """The `...` of Callable[..., R] and tuple[T, ...]: valid annotations."""
    allowed = set()
    for child in ast.walk(node):
        if not isinstance(child, ast.Subscript) or not isinstance(
            child.slice, ast.Tuple
        ):
            continue
        name = ast.unparse(child.value).rsplit(".", 1)[-1]
        elements = child.slice.elts
        if name == "Callable" and elements and _is_ellipsis(elements[0]):
            allowed.add(id(elements[0]))
        if name in ("tuple", "Tuple") and len(elements) == 2 and _is_ellipsis(
            elements[1]
        ):
            allowed.add(id(elements[1]))
    return allowed


def _unresolved(node):
    """Reason why the annotation or default value is not resolved, if any."""
    allowed = _typing_ellipses(node)
    for child in ast.walk(node):
        if _is_ellipsis(child) and id(child) not in allowed:
            return "unresolved `...`"
        if isinstance(child, ast.Constant) and isinstance(child.value, str):
            if RAW_CPP_NAME.search(child.value):
                return "raw C++ type name '%s'" % child.value
        if isinstance(child, ast.Name) and "::" in child.id:
            return "raw C++ type name '%s'" % child.id
    return None


def _parameters(function):
    arguments = function.args
    parameters = arguments.posonlyargs + arguments.args + arguments.kwonlyargs
    return parameters + [p for p in (arguments.vararg, arguments.kwarg) if p]


def _defaults(function):
    arguments = function.args
    return list(arguments.defaults) + [d for d in arguments.kw_defaults if d]


def _is_bind_vector(class_node):
    names = {
        n.name for n in class_node.body if isinstance(n, ast.FunctionDef)
    }
    return BIND_VECTOR_MARKERS <= names


def _check_function(function, owner, allowed, where, errors):
    qualified = "%s.%s" % (owner.name, function.name) if owner else function.name
    arg_allowed = qualified in allowed or (
        owner is not None
        and _is_bind_vector(owner)
        and function.name in BIND_VECTOR_MEMBERS
    )
    for parameter in _parameters(function):
        if ARG_NAME.fullmatch(parameter.arg) and not arg_allowed:
            errors.append(
                "%s:%d: %s: unnamed parameter '%s' (bind it with pybind11::arg)"
                % (where, function.lineno, qualified, parameter.arg)
            )
        if parameter.annotation is not None:
            reason = _unresolved(parameter.annotation)
            if reason:
                errors.append(
                    "%s:%d: %s: parameter '%s': %s"
                    % (where, function.lineno, qualified, parameter.arg, reason)
                )
    if function.returns is not None:
        reason = _unresolved(function.returns)
        if reason:
            errors.append(
                "%s:%d: %s: return type: %s"
                % (where, function.lineno, qualified, reason)
            )
    # A default value `= ...` is how stubgen writes a value it cannot
    # represent: only a raw C++ name in it is an error.
    for default in _defaults(function):
        for child in ast.walk(default):
            if isinstance(child, ast.Constant) and isinstance(child.value, str):
                if RAW_CPP_NAME.search(child.value):
                    errors.append(
                        "%s:%d: %s: default value: raw C++ type name '%s'"
                        % (where, function.lineno, qualified, child.value)
                    )


def check_stub(path, allowed):
    errors = []
    with open(path, encoding="utf-8") as stub:
        source = stub.read()
    try:
        tree = ast.parse(source, filename=path)
    except SyntaxError as error:
        return ["%s:%s: invalid stub: %s" % (path, error.lineno, error.msg)]

    def visit(body, owner):
        for node in body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                _check_function(node, owner, allowed, path, errors)
            elif isinstance(node, ast.ClassDef):
                visit(node.body, node)
            elif isinstance(node, ast.AnnAssign):
                if ast.unparse(node.annotation) == "typing.TypeVar":
                    errors.append(
                        "%s:%d: TypeVar written as an annotation (run "
                        "check_python_stubs.py fix)" % (path, node.lineno)
                    )
                    continue
                reason = _unresolved(node.annotation)
                if reason:
                    errors.append(
                        "%s:%d: attribute annotation: %s"
                        % (path, node.lineno, reason)
                    )

    visit(tree.body, None)
    return errors


def stub_files(paths):
    files = []
    for path in paths:
        if os.path.isdir(path):
            for root, _, names in os.walk(path):
                files += [
                    os.path.join(root, n) for n in sorted(names) if n.endswith(".pyi")
                ]
        else:
            files.append(path)
    return files


def run_stubs(paths, allowed):
    files = stub_files(paths)
    if not files:
        print("error: no .pyi stub found in %s" % " ".join(paths))
        return 1
    errors = []
    for path in files:
        errors += check_stub(path, set(allowed))
    for error in errors:
        print(error)
    print("Checked %d stub files: %d error(s)" % (len(files), len(errors)))
    return 1 if errors else 0


def fix_stubs(paths):
    """Rewrite `_T: typing.TypeVar` as `_T = typing.TypeVar("_T")`."""
    files = stub_files(paths)
    for path in files:
        with open(path, encoding="utf-8") as stub:
            source = stub.read()
        fixed = TYPEVAR_ANNOTATION.sub(r'\1 = typing.TypeVar("\1")', source)
        if fixed != source:
            with open(path, "w", encoding="utf-8", newline="") as stub:
                stub.write(fixed)
    return files


def copy_stubs(source, destination):
    for root, _, names in os.walk(source):
        for name in names:
            if name.endswith(".pyi"):
                target = os.path.join(
                    destination, os.path.relpath(os.path.join(root, name), source)
                )
                os.makedirs(os.path.dirname(target), exist_ok=True)
                shutil.copyfile(os.path.join(root, name), target)


def run_stubtest(modules, extra_arguments):
    command = [sys.executable, "-m", "mypy.stubtest"] + extra_arguments + modules
    result = subprocess.run(
        command, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True
    )
    # A mypy error makes stubtest check nothing: report it as is
    if "not checking stubs due to mypy build errors" in result.stdout:
        print(result.stdout)
        return 1
    ignored = [re.compile(pattern) for pattern in PYBIND11_ARTEFACTS]
    blocks = re.split(r"\n(?=error: )", result.stdout)
    remaining = []
    for block in blocks:
        if not block.startswith("error: "):
            continue
        message = block[len("error: ") :]
        if not any(pattern.match(message) for pattern in ignored):
            remaining.append(block)
    # stubtest ends with "Success: no issues found in N modules" or "Found N
    # errors (checked M modules)": anything else (mypy missing, crash, ...) means
    # that nothing was checked, which must not pass
    if result.returncode == 0:
        if "Success: no issues found" not in result.stdout:
            print(result.stdout)
            print("error: stubtest gave no result")
            return 1
    elif not re.search(r"^Found \d+ errors? \(checked \d+ modules?\)", result.stdout, re.M):
        print(result.stdout)
        print("error: stubtest did not run (exit code %d)" % result.returncode)
        return result.returncode or 1
    for block in remaining:
        print(block)
    print(
        "stubtest: %d error(s) after ignoring the pybind11 artefacts"
        % len(remaining)
    )
    return 1 if remaining else 0


def run_modules(modules, allowed, config, stubtest):
    """Generate the stubs of the importable modules, then run both gates."""
    with tempfile.TemporaryDirectory() as directory:
        for module in modules:
            command = [
                sys.executable,
                "-m",
                "pybind11_stubgen",
                "--exit-code",
                "-o",
                directory,
                module,
            ]
            if subprocess.run(command).returncode:
                print("error: pybind11-stubgen failed on %s" % module)
                return 1
        fix_stubs([directory])
        status = run_stubs([directory], allowed)
        if not stubtest:
            return status
        environment = os.environ.get("MYPYPATH")
        os.environ["MYPYPATH"] = os.pathsep.join(
            [directory] + ([environment] if environment else [])
        )
        extra = ["--mypy-config-file", config] if config else []
        return run_stubtest(modules, extra) or status


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)
    stubs = sub.add_parser("stubs")
    stubs.add_argument("paths", nargs="+")
    stubs.add_argument("--allow", action="append", default=[])
    fix = sub.add_parser("fix")
    fix.add_argument("paths", nargs="+")
    stubtest = sub.add_parser("stubtest")
    stubtest.add_argument("modules", nargs="+")
    stubtest.add_argument("--mypy-config-file")
    stubtest.add_argument("--stubs-from")
    modules = sub.add_parser("modules")
    modules.add_argument("modules", nargs="+")
    modules.add_argument("--allow", action="append", default=[])
    modules.add_argument("--mypy-config-file")
    modules.add_argument("--no-stubtest", action="store_true")
    arguments = parser.parse_args()
    if arguments.command == "modules":
        return run_modules(
            arguments.modules,
            arguments.allow,
            arguments.mypy_config_file,
            not arguments.no_stubtest,
        )
    if arguments.command == "fix":
        if not fix_stubs(arguments.paths):
            print("error: no .pyi stub found in %s" % " ".join(arguments.paths))
            return 1
        return 0
    if arguments.command == "stubs":
        return run_stubs(arguments.paths, arguments.allow)
    extra = []
    if arguments.mypy_config_file:
        extra = ["--mypy-config-file", arguments.mypy_config_file]
    if not arguments.stubs_from:
        return run_stubtest(arguments.modules, extra)
    with tempfile.TemporaryDirectory() as directory:
        source = os.path.abspath(arguments.stubs_from)
        copy_stubs(source, os.path.join(directory, os.path.basename(source)))
        environment = os.environ.get("MYPYPATH")
        os.environ["MYPYPATH"] = os.pathsep.join(
            [directory] + ([environment] if environment else [])
        )
        return run_stubtest(arguments.modules, extra)


if __name__ == "__main__":
    sys.exit(main())

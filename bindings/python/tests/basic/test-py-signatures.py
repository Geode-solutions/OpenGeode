"""Check that every public function of the Python modules is documented:
named arguments (no arg0, arg1...) and a non-empty docstring.

The modules are the ones listed in MODULES; the same walker is meant to be
reused for the other OpenGeode Python modules."""

import enum
import importlib
import inspect
import re
import sys

import geode_test_env

MODULES = [
    "opengeode_py_basic",
    "opengeode_py_geometry",
    "opengeode_py_image",
    "opengeode_py_gdal",
    "opengeode_py_mesh",
    "opengeode_py_model",
]
# Python wrappers defined in the .py files shipped next to the extensions
PYTHON_MODULES = ["basic", "geometry", "image", "gdal", "mesh", "model"]

GENERATED_ARG = re.compile(r"\barg\d+\b")
SIGNATURE = re.compile(r"^(?:\d+\. )?(?P<name>[\w.]+)\((?P<args>.*)\) -> .*$")
# pybind11 helper classes and containers generated by pybind11 itself, whose
# signatures and docstrings are not under our control
PYBIND11_GENERATED = {
    "opengeode_py_basic.ostream_redirect",
    "opengeode_py_gdal.ostream_redirect",
    "opengeode_py_geometry.ostream_redirect",
    "opengeode_py_image.ostream_redirect",
    "opengeode_py_mesh.ostream_redirect",
    "opengeode_py_model.ostream_redirect",
}
# Containers made by pybind11::bind_vector: only their docstring is ours, the
# generated methods have unnamed arguments
PYBIND11_CONTAINERS = {"opengeode_py_basic.AdditionalFileList"}
# Methods whose behavior is fixed by Python and documented there
EXEMPT_DOC = {
    "__eq__",
    "__ne__",
    "__lt__",
    "__le__",
    "__gt__",
    "__ge__",
    "__hash__",
    "__str__",
    "__repr__",
    "__setstate__",
    "__getstate__",
    "__reduce__",
    "__reduce_ex__",
    "__format__",
    "__sizeof__",
    "__dir__",
    "__init_subclass__",
    "__subclasshook__",
    "__new__",
    "__delattr__",
    "__getattribute__",
    "__setattr__",
    "__class__",
    "__doc__",
    "__module__",
    "__dict__",
    "__weakref__",
    "__members__",
    "__getitem__",
    "__setitem__",
    "__len__",
    "__iter__",
    "__bool__",
    "__contains__",
    "__call__",
    "__iadd__",
    "__isub__",
    "__imul__",
    "__itruediv__",
    "__add__",
    "__sub__",
    "__mul__",
    "__truediv__",
    "__radd__",
    "__rsub__",
    "__rmul__",
    "__rtruediv__",
    "__neg__",
}


def split_overloads(doc):
    """Return the [(signature_line, description)] found in a pybind11 doc."""
    lines = doc.split("\n")
    entries = []
    for line in lines:
        if SIGNATURE.match(line.strip()) and (
            not entries or line.lstrip()[:1].isdigit() or len(entries) == 0
        ):
            entries.append([line.strip(), []])
        elif entries:
            entries[-1][1].append(line.strip())
    if len(entries) == 0:
        return []
    return [(sig, " ".join(desc).strip()) for sig, desc in entries]


def is_pybind_callable(member):
    return (
        type(member).__name__
        in ("builtin_function_or_method", "instancemethod", "method_descriptor")
        and getattr(member, "__doc__", None) is not None
    )


CHECKED = []


def check_callable(qualified_name, member, problems, check_doc=True):
    CHECKED.append(qualified_name)
    doc = getattr(member, "__doc__", None) or ""
    entries = split_overloads(doc)
    if not entries:
        if check_doc and not doc.strip():
            problems.append(f"{qualified_name}: no docstring")
        return
    for signature, description in entries:
        if GENERATED_ARG.search(signature):
            problems.append(f"{qualified_name}: unnamed argument in {signature}")
        if check_doc and not description:
            problems.append(f"{qualified_name}: empty docstring for {signature}")


def check_class(qualified_name, cls, problems, seen):
    if id(cls) in seen or qualified_name in PYBIND11_GENERATED:
        return
    seen.add(id(cls))
    if issubclass(cls, enum.Enum):
        if not (cls.__doc__ or "").strip():
            problems.append(f"{qualified_name}: enum without docstring")
        return
    if not (cls.__doc__ or "").strip():
        problems.append(f"{qualified_name}: class without docstring")
    check_constructor(qualified_name, cls, problems)
    if qualified_name in PYBIND11_CONTAINERS:
        return
    for name, member in vars(cls).items():
        if name.startswith("_") and not (name.startswith("__") and name.endswith("__")):
            continue
        member_name = f"{qualified_name}.{name}"
        if member_name in PYBIND11_GENERATED:
            continue
        if isinstance(member, (staticmethod, classmethod)):
            member = member.__func__
        if isinstance(member, property):
            if not (member.__doc__ or "").strip():
                problems.append(f"{member_name}: property without docstring")
            for accessor in (member.fget, member.fset):
                if accessor is not None and GENERATED_ARG.search(
                    accessor.__doc__ or ""
                ):
                    problems.append(
                        f"{member_name}: unnamed argument in {accessor.__doc__.splitlines()[0]}"
                    )
            continue
        if inspect.isclass(member):
            check_class(member_name, member, problems, seen)
        elif is_pybind_callable(member):
            check_callable(member_name, member, problems, name not in EXEMPT_DOC)
        elif inspect.isfunction(member):
            check_python_function(member_name, member, problems)


# Docstring of object.__init__, inherited by a pybind11 class without
# constructor (help() then says nothing about how to get an instance)
GENERIC_INIT_DOC = "Initialize self."
MISSING_CONSTRUCTOR = "cannot be constructed directly"
NON_CONSTRUCTIBLE = []


def check_constructor(qualified_name, cls, problems):
    if issubclass(cls, BaseException):
        return
    doc = cls.__init__.__doc__ or ""
    if doc.startswith(GENERIC_INIT_DOC):
        problems.append(f"{qualified_name}: generic __init__ docstring")
    elif MISSING_CONSTRUCTOR in doc:
        NON_CONSTRUCTIBLE.append((qualified_name, cls))


def check_missing_constructors(problems):
    """The classes without constructor raise a TypeError telling how to get
    an instance, with or without arguments."""
    for qualified_name, cls in NON_CONSTRUCTIBLE:
        for arguments in ((), (1,)):
            try:
                cls(*arguments)
            except TypeError as error:
                if not arguments and MISSING_CONSTRUCTOR not in str(error):
                    problems.append(f"{qualified_name}(): wrong error {error}")
            else:
                problems.append(f"{qualified_name}{arguments} did not raise")
    names = {name for name, _ in NON_CONSTRUCTIBLE}
    for dimension in (2, 3):
        name = f"opengeode_py_mesh.RegularGrid{dimension}D"
        cls = importlib.import_module("opengeode_py_mesh").__dict__[name.split(".")[1]]
        if name not in names:
            problems.append(f"{name}: not documented as non-constructible")
        elif f"RegularGrid{dimension}D.create" not in cls.__init__.__doc__:
            problems.append(f"{name}: the __init__ docstring should point to create")
        if not isinstance(cls.create(), cls):
            problems.append(f"{name}.create does not return a {name}")
    # create is only suggested when the class defines it (an inherited one
    # returns the base class)
    for name, cls in NON_CONSTRUCTIBLE:
        suggested = ".create" in cls.__init__.__doc__
        if suggested != ("create" in vars(cls)):
            problems.append(f"{name}: wrong create suggestion in {cls.__init__.__doc__}")
    # The classes with only static methods are not obtained, they are used
    # through the class (libraries, factories)
    for name, cls in NON_CONSTRUCTIBLE:
        public = [
            member
            for base in cls.__mro__
            if base.__name__ not in ("pybind11_object", "object")
            for member_name, member in vars(base).items()
            if not member_name.startswith("_")
        ]
        static_only = bool(public) and all(
            isinstance(member, staticmethod) for member in public
        )
        documented = "has only static methods" in cls.__init__.__doc__
        if "create" not in vars(cls) and static_only != documented:
            problems.append(f"{name}: wrong static-only text in {cls.__init__.__doc__}")
    mesh_module = importlib.import_module("opengeode_py_mesh")
    for cls, method in [
        (mesh_module.OpenGeodeMeshLibrary, "initialize"),
        (mesh_module.TriangulatedSurfaceInputFactory3D, "has_creator"),
        (mesh_module.MeshFactory, None),
    ]:
        doc = cls.__init__.__doc__
        if "has only static methods" not in doc or "a builder, a loader" in doc:
            problems.append(f"{cls.__name__}: not documented as static-only: {doc}")
        if method and f"{cls.__name__}.{method}(...)" not in doc:
            problems.append(f"{cls.__name__}: the docstring should show {method}")
        if method:
            getattr(cls, method)
    corner = importlib.import_module("opengeode_py_model").Corner3D
    if "a builder, a loader or the object owning it" not in corner.__init__.__doc__:
        problems.append("Corner3D: no hint to get an instance")
    if len(NON_CONSTRUCTIBLE) < 150:
        problems.append(f"only {len(NON_CONSTRUCTIBLE)} non-constructible classes seen")


GENERIC_KINDS = [inspect.Parameter.VAR_POSITIONAL, inspect.Parameter.VAR_KEYWORD]


def check_python_function(qualified_name, function, problems):
    if not (function.__doc__ or "").strip():
        problems.append(f"{qualified_name}: no docstring")
    signature = inspect.signature(function)
    # inspect.signature follows __wrapped__, getfullargspec (used by
    # pybind11-stubgen) does not
    spec = inspect.getfullargspec(function)
    if spec.varargs and spec.varkw and not spec.args and not spec.kwonlyargs:
        # Typed overloads written as a pybind11 docstring (read by
        # pybind11-stubgen), e.g. basic.builder: checked as a binding, and
        # its runtime signature (__wrapped__) must be annotated
        if [p.kind for p in signature.parameters.values()] == GENERIC_KINDS:
            problems.append(f"{qualified_name}: no __wrapped__ runtime signature")
        entries = split_overloads(function.__doc__ or "")
        names = {SIGNATURE.match(entry[0]).group("name") for entry in entries}
        if names != {function.__name__}:
            problems.append(f"{qualified_name}: no signature in the docstring")
        for entry in entries:
            if not SIGNATURE.match(entry[0]).group("args"):
                problems.append(f"{qualified_name}: unannotated {entry[0]}")
        check_callable(qualified_name, function, problems)
        return
    for name, parameter in signature.parameters.items():
        if name in ("self", "cls"):
            continue
        if parameter.annotation is inspect.Parameter.empty:
            problems.append(f"{qualified_name}: parameter {name} is not annotated")
    if signature.return_annotation is inspect.Signature.empty:
        problems.append(f"{qualified_name}: no return annotation")


def check_module(module, problems, seen):
    for name, member in vars(module).items():
        if name.startswith("_"):
            continue
        qualified_name = f"{module.__name__}.{name}"
        if inspect.ismodule(member):
            if member.__name__.startswith(module.__name__):
                check_module(member, problems, seen)
        elif inspect.isclass(member):
            if member.__module__ == module.__name__ or member.__module__ in MODULES:
                check_class(qualified_name, member, problems, seen)
        elif is_pybind_callable(member):
            check_callable(qualified_name, member, problems)
    if not (module.__doc__ or "").strip():
        problems.append(f"{module.__name__}: no module docstring")


def check_python_module(module, problems):
    for name, member in vars(module).items():
        if name.startswith("_") or not inspect.isfunction(member):
            continue
        if member.__module__ == module.__name__:
            check_python_function(f"{module.__name__}.{name}", member, problems)


def check_sanity():
    """The checker itself must see unnamed arguments and missing docs."""
    problems = []

    class Fake:
        __doc__ = "f(arg0: int, arg1: int) -> int\n"

    check_callable("fake", Fake, problems)
    assert any("unnamed argument" in p for p in problems), problems
    assert any("empty docstring" in p for p in problems), problems
    overloaded = (
        "Overloaded function.\n\n1. f(a: int) -> int\n\nDoc one\n\n"
        "2. f(arg0: float) -> int\n\nDoc two\n"
    )
    entries = split_overloads(overloaded)
    assert [e[1] for e in entries] == ["Doc one", "Doc two"], entries

    class Plain:
        """A class without constructor"""

    problems = []
    check_constructor("plain", Plain, problems)
    assert problems == ["plain: generic __init__ docstring"], problems


if __name__ == "__main__":
    check_sanity()
    problems = []
    seen = set()
    for module_name in MODULES:
        check_module(importlib.import_module(module_name), problems, seen)
    for module_name in PYTHON_MODULES:
        check_python_module(importlib.import_module(module_name), problems)
    check_missing_constructors(problems)
    # The walker must really visit the bindings, not silently skip them
    assert len(CHECKED) > 1400, f"only {len(CHECKED)} callables were checked"
    if problems:
        print(f"{len(problems)} documentation problem(s):")
        for problem in sorted(set(problems)):
            print("  " + problem)
        sys.exit(1)
    print(
        "All public functions of "
        + ", ".join(MODULES)
        + f" have named arguments and a docstring ({len(CHECKED)} callables checked)"
    )

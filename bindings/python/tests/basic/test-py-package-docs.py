"""The documentation of the package (help(opengeode), opengeode.__doc__) and
its examples stay correct: the examples are executed as doctests, every public
function named by the documentation exists, and the generated __init__.py of
the wheel carries the same text.

Arguments: the text file of the documentation, the wheel package directory
generated by CMake."""

import doctest
import io
import os
import pydoc
import re
import sys

import geode_test_env

import opengeode


def check(condition, message):
    if not condition:
        raise ValueError(f"[Test] {message}")


def read_documentation(path):
    with open(path, encoding="utf-8") as file:
        return file.read()


def check_package_docstring(documentation):
    check(opengeode.__doc__ == documentation, "__doc__ is not the documentation file")
    text = pydoc.render_doc(opengeode, renderer=pydoc.plaintext)
    check("Five workflows" in text, "help(opengeode) lacks the workflows")
    for section in [
        "Build a mesh",
        "Save",
        "Load and inspect",
        "Attributes",
        "Numpy bulk access",
        "Generic functions",
        "Errors",
        "Logging and progress",
        "Good to know",
    ]:
        check(section in documentation, f"Section {section} is missing")
    for name in ["OpenGeodeDataError", "OpenGeodeInternalError", "OpenGeodeResultError"]:
        check(name in documentation, f"{name} is not documented")
    for claim in [
        "mutating a point mutates the geometry",
        "hashable by value",
        "MYPYPATH",
        "forward_logs_to_python",
    ]:
        check(claim in " ".join(documentation.split()), f"The documentation lacks: {claim}")


DOCUMENTED_API = [
    "load", "load_all", "save", "is_loadable", "is_saveable", "input_extensions",
    "output_extensions", "additional_files", "builder", "builder_type",
    "find_attribute", "registered_types", "register_type", "extend_type",
    "type_operation", "object_operation", "forward_logs_to_python",
    "stop_forwarding_logs", "add_progress_listener", "remove_progress_listener",
    "OpenGeodeError", "OpenGeodeDataError", "OpenGeodeInternalError",
    "OpenGeodeResultError", "ProgressEvent", "Percentage", "BRep", "Section",
    "TriangulatedSurface3D", "Segment3D", "Triangle3D", "Point3D", "Vector3D", "uuid",
]


def check_named_functions_exist(documentation):
    for name in DOCUMENTED_API:
        check(name in documentation, f"{name} is not mentioned by the documentation")
        check(hasattr(opengeode, name), f"opengeode.{name} does not exist")


def check_mesh_methods_named():
    surface = opengeode.TriangulatedSurface3D.create()
    builder = opengeode.builder(surface)
    for name in ["create_points", "create_triangles"]:
        check(hasattr(builder, name), f"builder.{name} does not exist")
    for name in [
        "points_array", "triangles_array", "polygons_array", "nb_vertices",
        "nb_polygons", "point", "vertex_attribute_manager", "triangle",
    ]:
        check(hasattr(surface, name), f"mesh.{name} does not exist")
    check(hasattr(opengeode.TetrahedralSolid3D, "tetrahedra_array"), "tetrahedra_array")
    check(hasattr(opengeode.EdgedCurve3D, "edges_array"), "edges_array")
    check(hasattr(opengeode.Graph, "edges_array"), "Graph.edges_array")
    check(hasattr(opengeode.GraphBuilder, "create_edges_with_vertices"), "Graph create_edges")
    check(not hasattr(opengeode.Graph, "points_array"), "Graph has no points")
    check(not hasattr(opengeode.VertexSet, "points_array"), "VertexSet has no points")
    check(hasattr(opengeode.VariableAttributeDouble, "values_array"), "values_array")
    check(hasattr(opengeode.PolygonalSurfaceBuilder3D, "create_polygons"), "create_polygons")
    check(hasattr(opengeode.EdgedCurveBuilder3D, "create_edges_with_vertices"), "create_edges")
    check(hasattr(opengeode.TetrahedralSolidBuilder3D, "create_tetrahedra"), "create_tetrahedra")
    check(opengeode.TRACE == 5, "opengeode.TRACE")
    check(hasattr(opengeode.Logger.Level, "info"), "Logger.Level.info")


def run_examples(documentation):
    parser = doctest.DocTestParser()
    test = parser.get_doctest(documentation, {"opengeode": opengeode}, "opengeode", None, 0)
    check(len(test.examples) >= 40, f"Only {len(test.examples)} examples")
    output = io.StringIO()
    runner = doctest.DocTestRunner(verbose=False, optionflags=doctest.ELLIPSIS)
    runner.run(test, out=output.write)
    results = runner.summarize(verbose=False)
    check(results.failed == 0, f"{results.failed} example(s) failed:\n{output.getvalue()}")
    # The examples leave the logs as they found them
    opengeode.stop_forwarding_logs()


def check_wheel_init(documentation, wheel_directory):
    init = os.path.join(wheel_directory, "__init__.py")
    with open(init, encoding="utf-8") as file:
        content = file.read()
    check('"""' + documentation + '"""' in content, "The wheel __init__.py lacks the documentation")
    code = [line for line in content.splitlines() if line and not line.startswith("#")]
    check(code[0].startswith('"""'), "The documentation is not the first statement of __init__.py")
    check(content.index('"""') < content.index("from .basic import"), "Documentation after the imports")
    import ast

    check(ast.get_docstring(ast.parse(content), clean=False) == documentation, "Wrong __init__.py docstring")


if __name__ == "__main__":
    documentation = read_documentation(sys.argv[1])
    check_package_docstring(documentation)
    check_named_functions_exist(documentation)
    check_mesh_methods_named()
    run_examples(documentation)
    check_wheel_init(documentation, sys.argv[2])

"""The wheel puts the extension modules at the root of the package, next to
__init__.py, and the shared libraries in a platform subfolder (lib, lib64 or
bin): the public path of the types (opengeode.opengeode_py_mesh...) is the same
on every platform. The extension modules must find the shared libraries of the
subfolder by themselves (rpath on Linux and macOS, os.add_dll_directory of
__init__.py on Windows).

The first argument is the wheel package directory generated by CMake, whose
pure-Python modules must import the extension modules from the package root."""

import importlib.machinery
import importlib.util
import os
import platform
import re
import shutil
import subprocess
import sys
import tempfile

import geode_test_env

MODULES = [
    "opengeode_py_basic",
    "opengeode_py_geometry",
    "opengeode_py_image",
    "opengeode_py_gdal",
    "opengeode_py_mesh",
    "opengeode_py_model",
]


def is_extension_module(name):
    # The shared libraries may have an extension module suffix (.so)
    return name.startswith("opengeode_py_") and any(
        name.endswith(suffix) for suffix in importlib.machinery.EXTENSION_SUFFIXES
    )


def make_package(directory):
    """Copy the build-tree extension modules to the package root and the shared
    libraries next to them in build tree to the platform subfolder."""
    package = os.path.join(directory, "package")
    os.makedirs(package)
    open(os.path.join(package, "__init__.py"), "w").close()
    build_directory = os.path.dirname(importlib.util.find_spec(MODULES[0]).origin)
    libraries = os.path.join(package, os.path.basename(build_directory))
    os.makedirs(libraries)
    for module in MODULES:
        origin = importlib.util.find_spec(module).origin
        shutil.copy(origin, os.path.join(package, os.path.basename(origin)))
    for name in os.listdir(build_directory):
        path = os.path.join(build_directory, name)
        if os.path.isfile(path) and not is_extension_module(name) and not name.endswith(".py"):
            shutil.copy(path, os.path.join(libraries, name))
    return libraries


def run_in_package(directory, libraries, code):
    environment = dict(os.environ)
    # The libraries of the build tree must not be found through the environment
    for variable in ("LD_LIBRARY_PATH", "DYLD_LIBRARY_PATH"):
        environment.pop(variable, None)
    if platform.system() == "Windows":
        # What the __init__.py of the wheel does
        environment["GEODE_DLL_DIRECTORIES"] = os.pathsep.join(
            [libraries, environment.get("GEODE_DLL_DIRECTORIES", "")]
        )
    environment["PYTHONPATH"] = os.pathsep.join(
        [directory, os.path.dirname(geode_test_env.__file__)]
    )
    return subprocess.run(
        [sys.executable, "-c", "import geode_test_env\n" + code],
        cwd=directory,
        env=environment,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
    )


def test_modules_at_package_root():
    with tempfile.TemporaryDirectory() as directory:
        libraries = make_package(directory)
        failures = []
        for module in MODULES:
            result = run_in_package(
                directory,
                libraries,
                f"import package.{module} as m\nassert m.__name__ == 'package.{module}'",
            )
            if result.returncode != 0:
                failures.append(f"{module}:\n{result.stdout}")
        if failures:
            raise ValueError(
                "[Test] Modules not importable from the package root:\n"
                + "\n".join(failures)
            )


def test_public_paths():
    with tempfile.TemporaryDirectory() as directory:
        libraries = make_package(directory)
        result = run_in_package(
            directory,
            libraries,
            "import pickle\n"
            "import package.opengeode_py_basic as basic\n"
            "import package.opengeode_py_geometry as geometry\n"
            "import package.opengeode_py_mesh as mesh\n"
            "mesh.OpenGeodeMeshLibrary.initialize()\n"
            "surface = mesh.TriangulatedSurface3D.create()\n"
            "assert type(surface).__module__ == 'package.opengeode_py_mesh', type(surface).__module__\n"
            "assert basic.OpenGeodeError.__module__ == 'package.opengeode_py_basic'\n"
            "assert repr(basic.OpenGeodeDataError).startswith(\"<class 'package.opengeode_py_basic.\")\n"
            "point = geometry.Point3D([1.0, 2.0, 3.0])\n"
            "assert type(point).__module__ == 'package.opengeode_py_geometry'\n",
        )
        if result.returncode != 0:
            raise ValueError("[Test] Wrong public paths:\n" + result.stdout)


def test_wheel_sources(wheel_package):
    """The generated pure-Python modules import the extension modules of the
    package root, never through a platform subfolder."""
    sources = [
        os.path.join(wheel_package, name)
        for name in sorted(os.listdir(wheel_package))
        if name.endswith(".py")
    ]
    if not sources:
        raise ValueError("[Test] No generated module in " + wheel_package)
    subfolder_import = re.compile(r"from \.\w+\.opengeode_py_\w+ import")
    root_import = re.compile(r"^from \.opengeode_py_\w+ import", re.MULTILINE)
    modules_with_root_import = 0
    for source in sources:
        with open(source) as file:
            content = file.read()
        if subfolder_import.search(content):
            raise ValueError("[Test] Import through a platform subfolder in " + source)
        if root_import.search(content):
            modules_with_root_import += 1
    # Every pure-Python module but __init__.py imports its extension module
    if modules_with_root_import != len(sources) - 1:
        raise ValueError(
            "[Test] Every generated module should import its extension module "
            "from the package root: %d of %d" % (modules_with_root_import, len(sources) - 1)
        )


if __name__ == "__main__":
    test_modules_at_package_root()
    test_public_paths()
    test_wheel_sources(sys.argv[1])
